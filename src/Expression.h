#pragma once
// Инфиксная запись как синтаксический сахар над префиксной.
//
// Старый формат остаётся основным: "sum 1 2", "primes 30". Новый слой нужен
// только там, где игрок пишет математическое выражение:
//
//   1 + 2 * 3
//   (1 + 2) * 3
//   sum(1, 2) + 3
//   f(1 + 2, 3)
//
// Результат нормализации — обычные префиксные слова, которые понимают уже
// существующие вычислители Level и Function. Скобки и запятые в инфиксном
// выражении имеют настоящий смысл: скобки группируют, запятые разделяют
// аргументы вызова. Смешивать префиксный вызов и инфикс в одном выражении
// нельзя: для вызова в инфиксе используйте f(...).

#include <string>
#include <vector>

namespace expression {

// Есть ли в строке бинарный инфиксный оператор. Нужно для совместимости:
// если строка начинается с известной функции и операторов нет, её разбирает
// старый префиксный парсер.
bool hasInfixOperator(const std::string& text);

// Есть ли вызов вида f(...) без пробела перед '('. Такой ввод тоже
// разбирает новый парсер, даже если инфиксных операторов нет: запятые в
// вызове имеют настоящий смысл, а не служат разделителями.
bool hasCallSyntax(const std::string& text);

// Разбирает инфиксное выражение (с вызовами f(...), скобками и запятыми)
// и выдаёт эквивалентную префиксную запись. При ошибке возвращает false и
// заполняет error понятным сообщением.
bool normalize(const std::string& text, std::vector<std::string>& prefix,
               std::string& error);

}  // namespace expression
